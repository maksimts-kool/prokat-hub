#!/usr/bin/env bash
# Builds Prokat Hub and deploys it to a Zone.ee virtual server (no Docker there):
#   - the React client is built for $BASE_PATH and served by the API from its wwwroot;
#   - the API and the worker are self-contained linux-x64 builds that PM2 keeps running;
#   - Apache forwards $SITE_ORIGIN$BASE_PATH to the API through an .htaccess proxy rule;
#   - the database is the MariaDB from MyZone; the API applies migrations on startup.
#
# Usage: deploy/zone/deploy.sh   (settings in deploy/zone/zone.env, see zone.env.example)
#
# The first run writes $REMOTE_HOME/prokathub/{api,worker}.pm2.json on the server with generated secrets
# (JWT key, seed account passwords). Put the database password into DB_PASSWORD in api.pm2.json there and run
# this again; it then starts or reloads both apps. Register both files in MyZone (PM2 rakendused) so Zone keeps
# them running after a server restart.
set -euo pipefail

cd "$(dirname "$0")/../.."
CONFIG=deploy/zone/zone.env
if [[ ! -f $CONFIG ]]; then
  echo "Copy deploy/zone/zone.env.example to $CONFIG and fill it in." >&2
  exit 1
fi
# shellcheck source=/dev/null
source "$CONFIG"
for name in ZONE_SSH SITE_ORIGIN BASE_PATH APP_IP APP_PORT REMOTE_HOME WEB_ROOT DB_HOST DB_NAME DB_USER DB_SERVER_VERSION; do
  [[ -n ${!name:-} ]] || { echo "$name is not set in $CONFIG" >&2; exit 1; }
done

OUT=deploy/zone/out
REMOTE_DIR=$REMOTE_HOME/prokathub
WEB_DIR=$WEB_ROOT$BASE_PATH

echo "==> Building the client for $BASE_PATH/"
(cd client && pnpm install --frozen-lockfile --silent && VITE_API_URL=$BASE_PATH pnpm build --base="$BASE_PATH/")

echo "==> Publishing the API and the worker (linux-x64, self-contained)"
rm -rf deploy/zone/out
publish() {
  dotnet publish "server/$1/$1.csproj" -c Release -r linux-x64 --self-contained \
    -p:InvariantGlobalization=true -p:GenerateDocumentationFile=false -o "$OUT/$2" --nologo -v quiet
}
publish ProkatHub.Api api
publish ProkatHub.Worker worker
# Development settings (seed demo passwords, localhost database) must not reach the server.
rm -f "$OUT/api/appsettings.Development.json" "$OUT/worker/appsettings.Development.json"
mkdir -p "$OUT/api/wwwroot"
cp -R client/dist/. "$OUT/api/wwwroot/"

echo "==> Uploading to $ZONE_SSH:$REMOTE_DIR"
ssh "$ZONE_SSH" "mkdir -p '$REMOTE_DIR/api' '$REMOTE_DIR/worker' '$WEB_DIR'"
rsync -az --delete "$OUT/api/" "$ZONE_SSH:$REMOTE_DIR/api/"
rsync -az --delete "$OUT/worker/" "$ZONE_SSH:$REMOTE_DIR/worker/"

echo "==> Writing the proxy rule $WEB_DIR/.htaccess"
ssh "$ZONE_SSH" "cat > '$WEB_DIR/.htaccess'" <<EOF
# Prokat Hub: everything under $BASE_PATH goes to the API (PM2 app prokathub-api), which also serves the client.
# Generated by deploy/zone/deploy.sh.
RewriteEngine On
RewriteCond %{HTTP:Upgrade} =websocket [NC]
RewriteRule ^(.*)\$ ws://$APP_IP:$APP_PORT$BASE_PATH/\$1 [P,L]
RewriteRule ^(.*)\$ http://$APP_IP:$APP_PORT$BASE_PATH/\$1 [P,L]
EOF

echo "==> Writing the PM2 files"
settings=$(printf '{"remoteHome":"%s","siteOrigin":"%s","basePath":"%s","appIp":"%s","appPort":"%s","dbHost":"%s","dbName":"%s","dbUser":"%s","dbServerVersion":"%s"}' \
  "$REMOTE_HOME" "$SITE_ORIGIN" "$BASE_PATH" "$APP_IP" "$APP_PORT" "$DB_HOST" "$DB_NAME" "$DB_USER" "$DB_SERVER_VERSION")
state=$(ssh "$ZONE_SSH" "node - '$settings'" < deploy/zone/write-pm2-config.js)

if [[ $state == needs-db-password ]]; then
  cat <<EOF

The app is uploaded but not started: the database password is missing.
  1. ssh $ZONE_SSH
  2. Edit $REMOTE_DIR/api.pm2.json and replace __SET_DB_PASSWORD__ in "DB_PASSWORD" with the MyZone password.
  3. Run deploy/zone/deploy.sh again.
EOF
  exit 0
fi

echo "==> Starting or reloading the apps"
ssh "$ZONE_SSH" "pm2 startOrReload '$REMOTE_DIR/api.pm2.json' --update-env && pm2 startOrReload '$REMOTE_DIR/worker.pm2.json' --update-env && pm2 save --force >/dev/null"

echo "==> Waiting for $SITE_ORIGIN$BASE_PATH/health"
for _ in $(seq 1 30); do
  if [[ $(curl -s "$SITE_ORIGIN$BASE_PATH/health") == Healthy ]]; then
    echo "Deployed: $SITE_ORIGIN$BASE_PATH/"
    exit 0
  fi
  sleep 2
done
echo "The health check did not pass. Logs: ssh $ZONE_SSH 'pm2 logs prokathub-api --lines 50 --nostream'" >&2
exit 1
